//increment and decrement operators
let x = 5;
x++; // x is now 6
console.log(x);
x--; // x is now 5
console.log(x);



//assignment operators
let y = 10;
y += 5;
console.log(y); // Output: 15
y -= 3;
console.log(y); // Output: 12
y *= 2;
console.log(y); // Output: 24
y /= 4;
console.log(y); // Output: 6

