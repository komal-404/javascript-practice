// | Loop         | Main Purpose                                |
// | ------------ | ------------------------------------------- |
// | `for`        | Repeat something a known number of times    |
// | `while`      | Repeat while a condition is true            |
// | `do...while` | Execute at least once, then check condition |
// | `for...in`   | Loop through object keys/properties         |
// | `for...of`   | Loop through values of iterable objects     |
// | `forEach()`  | Execute a function for every array element  |



//for (initialization; condition; update)

console.log("____p1____");
for (let i=0;i<=10;i++){
    console.log(i);
}

console.log("____p2____");

for(let j=10;j>=1;j--){
    console.log(j);
}

console.log("____p3____");

for(let n=0;n<=10;n++){
    if(n%2==0){
        console.log(n);
    }
}

